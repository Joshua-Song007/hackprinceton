function walk(dir, base = dir) {
  return readdirSync(dir).sort().flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p, base) : [relative(base, p).replace(/\\/g, '/')];
  });
}

/** Files under OUT that differ from `generated`, or are extra / missing. */
export function stale(generated) {
  const bad = [];
  for (const [rel, text] of Object.entries(generated)) {
    const p = join(OUT, rel);
    if (!existsSync(p) || lf(readFileSync(p, 'utf8')) !== text) bad.push(rel);
  }
  const have = existsSync(join(OUT, 'scaffolds')) ? walk(join(OUT, 'scaffolds')).map((f) => `scaffolds/${f}`) : [];
  bad.push(...have.filter((f) => !(f in generated)));
  return bad;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const gen = generate();
  if (process.argv.includes('--check')) {
    const bad = stale(gen);
    if (bad.length) { console.error(`stale (run node Tools/pear-check/gen-skill.mjs):\n  ${bad.join('\n  ')}`); process.exit(1); }
    console.log('skill is up to date');
  } else {
    rmSync(join(OUT, 'scaffolds'), { recursive: true, force: true });
    for (const [rel, text] of Object.entries(gen)) {
      mkdirSync(dirname(join(OUT, rel)), { recursive: true });
      writeFileSync(join(OUT, rel), text);
    }
    console.log(`wrote ${Object.keys(gen).length} files under ${relative(ROOT, OUT)}`);
  }
}
