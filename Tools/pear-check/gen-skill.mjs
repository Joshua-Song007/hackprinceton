/** Table rows of one `## ` section of scripting-api.md under a `### <sub>` heading: [{sig, desc}]. */
export function tableRows(doc, section, sub) {
  const sec = doc.split(/^## /m).find((s) => s.startsWith(section));
  const part = sec?.split(/^### /m).find((s) => s.startsWith(sub));
  if (!part) throw new Error(`scripting-api.md: no "${section}" / "${sub}" section (generator needs updating)`);
  const rows = [...part.matchAll(/^\| `(.+?)` \| (.+) \|$/gm)].map((m) => ({ sig: m[1], desc: m[2] }));
  if (!rows.length) throw new Error(`scripting-api.md: "${section}" / "${sub}" has no table rows`);
  return rows;
}
const bullets = (rows) => rows.map((r) => `- \`${r.sig}\`: ${r.desc}`).join('\n');

/** Constants of manifest.ts, read as text so no TypeScript runtime is needed. */
export function manifestFacts(src) {
  const arr = (name) => {
    const m = src.match(new RegExp(`export const ${name} = \\[(.+?)\\] as const`));
    if (!m) throw new Error(`manifest.ts: ${name} not found (generator needs updating)`);
    return [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]);
  };
  const raise = src.match(/RAISE_DEFAULTS: RaiseGesture = \{ angleDeg: (\d+), hysteresisDeg: (\d+) \}/);
  const fmt = src.match(/MANIFEST_FORMAT = '([^']+)'/);
  if (!raise || !fmt) throw new Error('manifest.ts: RAISE_DEFAULTS or MANIFEST_FORMAT not found (generator needs updating)');
  return { keys: arr('MANIFEST_KEYS'), sensors: arr('SENSORS'), angleDeg: raise[1], hysteresisDeg: raise[2], format: fmt[1] };
}

